/**
 * Generates aesthetically balanced random regions on the canvas.
 */
export function generateRandomRegions(seed: number, count = 4): AsciiRegion[] {
  const rng = createPRNG(seed);
  const regions: AsciiRegion[] = [];

  for (let i = 0; i < count; i++) {
    const isWideStrip = rng() > 0.45;
    const w = isWideStrip ? randomRange(rng, 0.44, 0.84) : randomRange(rng, 0.24, 0.46);
    const h = isWideStrip ? randomRange(rng, 0.14, 0.28) : randomRange(rng, 0.24, 0.46);
    const x = randomRange(rng, 0.05, Math.max(0.06, 0.95 - w));
    const y = randomRange(rng, 0.05, Math.max(0.06, 0.95 - h));

    const family = FAMILIES[randomInt(rng, 0, FAMILIES.length - 1)];
    const color = COLORS[randomInt(rng, 0, COLORS.length - 1)];
    const cellSize = [10, 12, 14, 16, 18][randomInt(rng, 0, 4)];
    const substrateMode = SUBSTRATES[randomInt(rng, 0, SUBSTRATES.length - 1)];
    const shape = rng() > 0.82 ? 'ellipse' : 'rect';

    regions.push({
      id: `rgn-${seed}-${i}`,
      label: `Layer 0${i + 1}`,
      x: Number(x.toFixed(3)),
      y: Number(y.toFixed(3)),
      w: Number(w.toFixed(3)),
      h: Number(h.toFixed(3)),
      cellSize,
      glyphFamily: family,
      color,
      knockoutOpacity: Number(randomRange(rng, 0.86, 0.96).toFixed(2)),
      contrast: Number(randomRange(rng, 1.18, 1.38).toFixed(2)),
      substrateMode,
      shape,
      hudFrame: false,
    });
  }

  return regions;
}

